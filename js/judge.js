/* 判定エンジン — 韓国版アプリの js/judge.js を移した（韓国側の姉妹プロダクト用の判定エンジンを
   もとの韓国アプリ向けに直したものを、さらにこの日本語版フレーム用に書き直した）。
 * 日本語版では「概念名を文に差し込むときの助詞」を選ぶ仕組み（韓国語は語末に子音(パッチム)が
 * あるかどうかで助詞の形が変わる）が要らない。日本語の助詞は前の単語の音では変わらないので、
 * 文型ごとに助詞を固定で書けばよい — そのぶん韓国版よりだいぶ単純になっている。
 *
 *   concept・lecture → 「正しい文を読む」（この論点の〇の過去問をまとめて見せる — 作った解説ではない）
 *
 * 判定エンジン — 学習者が答えを出した**その瞬間**に何を言い、次に何を出すかを決める。
 *
 * 設計の考え方 —
 *   ① 学習者の行動   正誤 / 時間 / **確信度** / 再挑戦
 *   ② イベント保存    answer_submitted + skill_id
 *   ③ 判定エンジン    ルール + 習熟度 → **誤解の分類** → 次の行動を選ぶ
 *   ④ 即時フィードバック  一言の説明 — **概念名を入れてやわらかく**
 *   ⑤ 次の問題        やさしい／似た／復習 を自動で
 *
 * ★★ **AI を呼ばない。** ルールが 0.01 秒で決める。
 *   毎回長い文を作ると遅く、高くつき、言うことがそのたびに変わってしまう。
 *   試験対策サービスは**同じ状況に同じ言葉**を返してこそ学習者が信用する。
 *   （LLM を使うとしたら、この先の段階で判定結果を受け取って一言二言を整える役どころ。）
 *
 * ─────────────────────────────────────────────
 * このエンジンが分ける軸は **確信度 × 正誤** である。
 *
 *   確信 ＋ 正解 →  分かっている。        次へ進む
 *   確信 ＋ 不正解 →  **誤解している**   ★ 最も危ない。本人は合っていると信じている
 *   半々 ＋ 正解 →  運かもしれない。      同じ概念をもう一つ
 *   半々 ＋ 不正解 →  迷っている。         概念を確認してやさしい方から
 *   当てずっぽう ＋ 正解 →  運だ。         概念から
 *   当てずっぽう ＋ 不正解 →  分かっていない。  講義（正しい文を読む）へ
 *
 * 正解率だけ見るとこの 6 つが**2 つに潰れてしまう。** 確信して間違えたのと当てずっぽうで
 * 間違えたのは同じ「不正解」だが、やるべきことは正反対だ —
 * 前者は**信じていることを崩す**必要があり、後者は**最初から教える**必要がある。
 */
(function () {
  "use strict";

  /* ── しきい値 — 一箇所にまとめる ─────────────────────
     ★ 数字をコードのあちこちに散らすと、調整するときにずれてしまう。 */
  var T = {
    fast: 6000,          // これより速く答えたら「すぐ分かった」または「読んでいない」
    slow: 75000,         // これより時間がかかったら際どかった
    streakWrong: 3,      // 同じリーフでこの回数連続して間違えたら講義へ回す
    lowMastery: 0.55,    // これ未満ならそのリーフをまだ分かっていないと見る
    highMastery: 0.85    // これ以上なら次に進んでよい
  };

  /* 確信度 — 学習者が自分で選ぶ。値が無ければ（聞いていなければ）null */
  var 確信段階 = [
    { v: "sure", name: "確実です", w: 1.0 },
    { v: "half", name: "半々です", w: 0.5 },
    { v: "guess", name: "当てずっぽうです", w: 0.0 }
  ];

  /* ── フィードバック文 ──────────────────────────────
     ★★ **説教しない。** 不正解は失敗ではなく、もう一度やることだ。
       「知っていたことが崩れましたね」のような言い方は学習者を評価する言葉になる —
       高校 1 年生がその言葉を聞くと戻ってこない。
     ★★ **概念名を入れる。** `{concept}` の場所にそのリーフの名前が入る。
       「もう一度確認しましょう」より「**市民的不服従の条件**をもう一度確認しましょう」の方が
       ずっとよい — 何をすればいいかが文の中にあるからだ。
     ★ 名前が分からないときのために **名前なしの版**（`_x` サフィックス）も用意する。
     ★ 評価しない。**何をするかだけ**を言う。 */
  /* 画面に出る判定バッジ — kind は記録用の名前 */
  var ラベル = {
    know: "分かって正解", knowFast: "分かって正解", misconception: "間違って覚えていた", luck: "運で正解",
    confused: "迷い", guessRight: "当てずっぽうで正解", dontKnow: "まだ分からない", tooFastWrong: "早く答えすぎ",
    slowRight: "時間をかけて正解", right: "正解", wrong: "不正解", streakWrong: "連続不正解", retryRight: "もう一度解いて正解"
  };
  var 文言 = {
    /* 確信 ＋ 正解 */
    know: [
      "正確です。{concept}は次に進みましょう。",
      "{concept}は分かっています。次の問題へ行きましょう。"
    ],
    know_x: ["正確です。次に進みましょう。", "分かっています。次の問題へ行きましょう。"],

    knowFast: [
      "すぐに正解できました。{concept}は次に進みましょう。",
      "すぐに正解できました。{concept}は次に進みます。"
    ],
    knowFast_x: ["すぐに正解できました。次に進みましょう。", "すぐに正解できました。"],

    /* ★ 確信 ＋ 不正解 — 最も気をつける場面。「間違えました」とは言わない。**何を見直すか**だけ言う。 */
    misconception: [
      "確実だと思ったのに違いました。{concept}をもう一度見てみましょう。",
      "{concept}をもう一度読んでみましょう。",
      "{concept}は間違えやすいところです。もう一度見てみましょう。"
    ],
    misconception_x: [
      "確実だと思ったのに違いました。ここをもう一度見てみましょう。",
      "もう一度読んでみましょう。"
    ],

    /* 半々 ＋ 正解 */
    luck: [
      "正解しました。{concept}をもう一つ解いてみましょう。",
      "正解です。{concept}をもう一つ見てみましょう。"
    ],
    luck_x: ["正解しました。もう一つ解いてみましょう。", "正解です。もう一つ見てみましょう。"],

    /* 半々 ＋ 不正解 */
    confused: [
      "{concept}をもう一度読んでみましょう。",
      "{concept}はやさしい問題から見直しましょう。"
    ],
    confused_x: ["もう一度読んでみましょう。", "やさしい問題から見直しましょう。"],

    /* 当てずっぽう ＋ 正解 */
    guessRight: [
      "正解しましたが、当てずっぽうでした。{concept}を読んでおきましょう。",
      "{concept}を読んでおきましょう。"
    ],
    guessRight_x: ["正解しましたが、当てずっぽうでした。内容を読んでおきましょう。", "内容を読んでおきましょう。"],

    /* 当てずっぽう ＋ 不正解 */
    dontKnow: [
      "{concept}を先に読んでみましょう。",
      "{concept}はまだ習っていないところです。内容から読んでみましょう。"
    ],
    dontKnow_x: ["内容を先に読んでみましょう。", "まだ習っていないところです。内容から読んでみましょう。"],

    /* 確信度を聞かなかったとき */
    right: ["正解です。", "合っています。"],
    right_x: ["正解です。", "合っています。"],
    wrong: [
      "不正解です。{concept}をもう一度見てみましょう。",
      "不正解です。{concept}の根拠を読んでみましょう。"
    ],
    wrong_x: ["不正解です。もう一度見てみましょう。", "不正解です。根拠を読んでみましょう。"],

    /* 反応時間 */
    tooFastWrong: ["早く答えすぎました。最後まで読みましょう。"],
    tooFastWrong_x: ["早く答えすぎました。最後まで読みましょう。"],

    slowRight: ["正解です。時間がかかったので、{concept}をもう一つ解いてみましょう。"],
    slowRight_x: ["正解です。時間がかかったので、もう一つ解いてみましょう。"],

    /* 累積 */
    streakWrong: ["{concept}で何度も間違えました。内容から読んでみましょう。"],
    streakWrong_x: ["何度も間違えました。内容から読んでみましょう。"],

    retryRight: ["今回は正解しました。{concept}、この調子が一番長く残ります。"],
    retryRight_x: ["今回は正解しました。この調子が一番長く残ります。"]
  };

  /* `{concept}` という場所表示を概念名に置き換える。
     日本語は前の単語の音で助詞が変わらないので、韓国版のような助詞の付け替えは要らない —
     文型ごとに助詞を固定で書いておくだけでよい。 */
  function 名前差込み(文, 名前) {
    return String(文).replace(/\{concept\}/g, 名前);
  }

  /* 状況に合う言葉を選び、**概念名を差し込む。**
     ★ 名前が分からないときは `_x` 版（名前なしの文）を使う。
     ★ 無作為に選ぶとリロードのたびに言葉が変わる — 問題 id で固定する。 */
  function 選ぶ(キー, 種, 概念) {
    var 名前 = String(概念 || "").trim();
    /* 名前に付いた印（★ など）を外す — 文に混ざると不自然になる */
    名前 = 名前.replace(/\s*★\s*$/, "").trim();
    var a = 文言[名前 ? キー : (キー + "_x")] || 文言[キー] || 文言["right"];
    var h = 0, s = String(種 || "");
    for (var i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
    var t = a[h % a.length];
    return 名前 ? 名前差込み(t, 名前) : t.replace(/\{concept\}/g, "");
  }

  /* ── 判定 ─────────────────────────────────────
     入力 —
       ok        正解か
       conf      "sure" | "half" | "guess" | null（聞いていない）
       ms        答えるのにかかった時間（ミリ秒）
       attempt   この問題を何回目に解いているか（1 から）
       mastery   そのリーフの習熟度 0~1（分からなければ null）
       streak    そのリーフで連続して間違えた回数
     返すもの —
       kind      状況の名前（記録・統計に使う）
       say       学習者に見せる一言
       next      次に何を出すか
       urgent    今すぐ必ず取り上げるべきか（誤解）
  */
  function 判定(x) {
    x = x || {};
    var ok = !!x.ok;
    var conf = x.conf || null;
    var ms = x.ms || 0;
    var attempt = x.attempt || 1;
    var mastery = (x.mastery == null) ? null : x.mastery;
    var streak = x.streak || 0;
    var 種 = x.qid || "";
    var 概念 = x.leafName || "";        // ★ 文に入れる概念名

    var kind, next, urgent = false;

    /* ① 同じリーフで連続して間違える — 問題をもっと出すのは答えではない */
    if (!ok && streak + 1 >= T.streakWrong) {
      return { kind: "streakWrong", say: 選ぶ("streakWrong", 種, 概念),
               next: "lecture", urgent: true, tone: "warn" };
    }

    /* ② 解き直して正解した — 一番よく残る瞬間。短くほめて次へ */
    if (ok && attempt >= 2) {
      return { kind: "retryRight", say: 選ぶ("retryRight", 種, 概念),
               next: "forward", urgent: false, tone: "good" };
    }

    /* ③ 確信度 × 正誤 — このエンジンの骨組み */
    if (conf === "sure") {
      if (ok) {
        kind = (ms && ms < T.fast) ? "knowFast" : "know";
        next = (mastery != null && mastery >= T.highMastery) ? "skip" : "forward";
      } else {
        /* ★ 確信して不正解 ＝ 誤解。本人は合っていると信じている。必ず今崩す。 */
        kind = "misconception"; next = "same"; urgent = true;
      }
    } else if (conf === "half") {
      if (ok) { kind = "luck"; next = "similar"; }
      else { kind = "confused"; next = "easier"; }
    } else if (conf === "guess") {
      if (ok) { kind = "guessRight"; next = "concept"; }
      else { kind = "dontKnow"; next = "lecture"; }
    } else {
      /* 確信度を聞かなかった — 反応時間で代わりに分ける */
      if (!ok && ms && ms < T.fast) { kind = "tooFastWrong"; next = "same"; }
      else if (ok && ms && ms > T.slow) { kind = "slowRight"; next = "similar"; }
      else if (ok) { kind = "right"; next = "forward"; }
      else { kind = "wrong"; next = "same"; }
    }

    /* ④ 習熟度が低いのに正解した — 先に進まない */
    if (ok && mastery != null && mastery < T.lowMastery && next === "forward")
      next = "similar";

    /* ★ 誤解は**オレンジ**にする。ただの不正解とは違って見えるべきだ —
       「間違えた」ではなく「信じていたことが崩れた」からだ。
       赤にすると他の不正解に埋もれてしまう。 */
    return { kind: kind, label: ラベル[kind] || kind, say: 選ぶ(kind, 種, 概念), next: next, urgent: urgent,
             tone: urgent ? "warn" : (ok ? "good" : "bad") };
  }

  /* 次の行動を人の言葉で — 画面のボタン名に使う */
  var 次行動 = {
    forward: { t: "次の問題", why: "この概念は次に進みます" },
    skip:    { t: "次の概念へ", why: "この概念は分かっています" },
    same:    { t: "この概念をもう一つ", why: "同じ概念をもう一つ解きます" },
    similar: { t: "似た問題をもう一つ", why: "似た問題をもう一つ解きます" },
    easier:  { t: "やさしい方から", why: "やさしい問題から解きます" },
    concept: { t: "正しい文を読む", why: "この論点の正しい過去問をまとめて読みます" },
    lecture: { t: "正しい文を読む", why: "この論点の正しい過去問をまとめて読みます" }
  };

  window.JUDGE = {
    判定: 判定, 閾値: T, 確信段階: 確信段階, 次行動: 次行動,
    /* 検査スクリプトが使うもの — どんな状況名があるか */
    状況一覧: Object.keys(文言)
  };
})();
